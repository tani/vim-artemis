-- Generate lua/artemis/core/optinfo.lua from a running Neovim.
-- Usage: nvim -l scripts/gen_optinfo.lua > lua/artemis/core/optinfo.lua
local all = vim.api.nvim_get_all_options_info()
local names = vim.tbl_keys(all)
table.sort(names)
io.write('-- Generated by scripts/gen_optinfo.lua from Neovim ' .. (function() local v = vim.version() return v.major .. '.' .. v.minor .. '.' .. v.patch end)() .. '. Do not edit.\n')
io.write('-- name = { type, commalist, flaglist, scope(s), global_local, shortname, allows_duplicates }\n')
io.write('return {\n')
for _, n in ipairs(names) do
  local i = all[n]
  io.write(string.format(
    '  [%q] = { %q, %s, %s, %q, %s, %q, %s },\n',
    n, i.type, tostring(i.commalist), tostring(i.flaglist),
    i.scope, tostring(i.global_local), i.shortname or '', tostring(i.allows_duplicates)
  ))
end
io.write('}\n')
