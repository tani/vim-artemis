-- Generate lua/artemis/core/colors.lua from a running Neovim.
-- Usage: nvim -l scripts/gen_colors.lua > lua/artemis/core/colors.lua
local map = vim.api.nvim_get_color_map()
local names = vim.tbl_keys(map)
table.sort(names)
io.write('-- Generated by scripts/gen_colors.lua (name -> 0xRRGGBB). Do not edit.\nreturn {\n')
for _, n in ipairs(names) do
  io.write(string.format('  [%q] = 0x%06x,\n', n, map[n]))
end
io.write('}\n')
