#!/bin/sh
# Generate docs/compat-table.md: which nvim_* functions are emulated on Vim.
cd "$(dirname "$0")/.." || exit 1
export ARTEMIS_ROOT=$(pwd)
OUT=$(mktemp); IMPL=$(mktemp); NV=$(mktemp)
cat > "$OUT.lua" <<'LUA'
package.path = os.getenv('ARTEMIS_ROOT') .. '/lua/?.lua;' .. os.getenv('ARTEMIS_ROOT') .. '/lua/?/init.lua;' .. package.path
require('artemis.inject').setup()
local names = {}
for k in pairs(vim.api) do if type(k) == 'string' and k:match('^nvim_') then names[#names + 1] = k end end
table.sort(names)
local f = io.open(os.getenv('IMPL'), 'w'); f:write(table.concat(names, '\n') .. '\n'); f:close()
LUA
IMPL=$IMPL TERM=dumb timeout 60 vim -u NONE -i NONE -N --not-a-term -c "luafile $OUT.lua" -c "qa!" </dev/null >/dev/null 2>&1
cat > "$OUT.nv.lua" <<'LUA'
local out = {}
for _, f in ipairs(vim.fn.api_info().functions) do
  if f.name:match('^nvim_') and not f.deprecated_since and not f.name:match('^nvim__') then
    out[#out + 1] = f.name
  end
end
table.sort(out)
local f = io.open(os.getenv('NV'), 'w'); f:write(table.concat(out, '\n') .. '\n'); f:close()
LUA
NV=$NV nvim --headless -u NONE -l "$OUT.nv.lua" >/dev/null 2>&1
{
  echo "# vim.api coverage on Vim"
  echo
  echo "Generated by \`scripts/api_coverage.sh\` against $(nvim --version | head -1)."
  echo "Only non-deprecated, non-internal \`nvim_*\` functions are counted."
  echo
  TOTAL=$(wc -l < "$NV"); DONE=$(comm -12 "$NV" "$IMPL" | wc -l)
  echo "**Implemented: $DONE / $TOTAL**"
  echo
  echo "## Implemented"
  echo
  comm -12 "$NV" "$IMPL" | sed 's/^/- `/; s/$/`/'
  echo
  echo "## Not implemented"
  echo
  comm -23 "$NV" "$IMPL" | sed 's/^/- `/; s/$/`/'
} > docs/compat-table.md
rm -f "$OUT" "$OUT.lua" "$OUT.nv.lua" "$IMPL" "$NV"
head -8 docs/compat-table.md
