local api = vim.api
local function fresh(lines)
  vim.cmd('enew!')
  api.nvim_buf_set_lines(0, 0, -1, false, lines or { 'hello world', 'second line' })
  return api.nvim_get_current_buf()
end

describe('extmarks', function()
  it('set / get / del', function()
    local b = fresh()
    local ns = api.nvim_create_namespace('artemis_t1')
    local id = api.nvim_buf_set_extmark(b, ns, 1, 3, {})
    eq(api.nvim_buf_get_extmark_by_id(b, ns, id, {}), { 1, 3 })
    eq(api.nvim_buf_del_extmark(b, ns, id), true)
    eq(api.nvim_buf_get_extmark_by_id(b, ns, id, {}), {})
  end)
  it('get_extmarks lists in order', function()
    local b = fresh()
    local ns = api.nvim_create_namespace('artemis_t2')
    local a = api.nvim_buf_set_extmark(b, ns, 0, 5, {})
    local c = api.nvim_buf_set_extmark(b, ns, 1, 2, {})
    local marks = api.nvim_buf_get_extmarks(b, ns, 0, -1, {})
    eq({ #marks, marks[1][1], marks[2][1] }, { 2, a, c })
    eq({ marks[1][2], marks[1][3] }, { 0, 5 })
  end)
  it('namespaces are isolated; clear', function()
    local b = fresh()
    local n1 = api.nvim_create_namespace('artemis_t3a')
    local n2 = api.nvim_create_namespace('artemis_t3b')
    api.nvim_buf_set_extmark(b, n1, 0, 0, {})
    api.nvim_buf_set_extmark(b, n2, 0, 1, {})
    eq(#api.nvim_buf_get_extmarks(b, n1, 0, -1, {}), 1)
    api.nvim_buf_clear_namespace(b, n1, 0, -1)
    eq(#api.nvim_buf_get_extmarks(b, n1, 0, -1, {}), 0)
    eq(#api.nvim_buf_get_extmarks(b, n2, 0, -1, {}), 1)
  end)
  it('range with hl_group', function()
    local b = fresh()
    local ns = api.nvim_create_namespace('artemis_t4')
    local id = api.nvim_buf_set_extmark(b, ns, 0, 0, { end_row = 0, end_col = 5, hl_group = 'Search' })
    local m = api.nvim_buf_get_extmark_by_id(b, ns, id, { details = true })
    eq({ m[1], m[2] }, { 0, 0 })
  end)
  it('marks survive set_text (shift after, keep before)', function()
    local b = fresh({ 'f(a, b)' })
    local ns = api.nvim_create_namespace('artemis_t5')
    local m1 = api.nvim_buf_set_extmark(b, ns, 0, 1, {})
    local m2 = api.nvim_buf_set_extmark(b, ns, 0, 6, {})
    api.nvim_buf_set_text(b, 0, 2, 0, 2, { '', '' })
    eq(api.nvim_buf_get_extmark_by_id(b, ns, m1, {}), { 0, 1 })
    eq(api.nvim_buf_get_extmark_by_id(b, ns, m2, {}), { 1, 4 })
  end)
  it('add_highlight returns ns and clear works', function()
    local b = fresh()
    local ns = api.nvim_create_namespace('artemis_t6')
    eq(api.nvim_buf_add_highlight(b, ns, 'Search', 0, 0, 5), ns)
    api.nvim_buf_clear_namespace(b, ns, 0, -1)
    eq(#api.nvim_buf_get_extmarks(b, ns, 0, -1, {}), 0)
  end)
end)

describe('floating windows', function()
  it('open / config / close', function()
    fresh()
    local b = api.nvim_create_buf(false, true)
    api.nvim_buf_set_lines(b, 0, -1, false, { 'float' })
    local cur = api.nvim_get_current_win()
    local w = api.nvim_open_win(b, false, { relative = 'editor', row = 2, col = 4, width = 12, height = 3, border = 'single' })
    eq(api.nvim_win_is_valid(w), true)
    eq(api.nvim_win_get_buf(w), b)
    eq(api.nvim_win_get_config(w).relative, 'editor')
    eq(api.nvim_get_current_win(), cur)
    eq(api.nvim_win_get_config(cur).relative, '')
    api.nvim_win_close(w, true)
    eq(api.nvim_win_is_valid(w), false)
  end)
  it('nvim_win_call on a float', function()
    fresh()
    local b = api.nvim_create_buf(false, true)
    api.nvim_buf_set_lines(b, 0, -1, false, { 'a', 'b', 'c' })
    local w = api.nvim_open_win(b, false, { relative = 'editor', row = 1, col = 1, width = 5, height = 3 })
    local r = api.nvim_win_call(w, function() return vim.fn.line('$') end)
    eq(r, 3)
    api.nvim_win_set_cursor(w, { 2, 0 })
    eq(api.nvim_win_get_cursor(w), { 2, 0 })
    api.nvim_win_close(w, true)
  end)
end)

describe('buffer attach and marks', function()
  it('on_lines fires', function()
    local b = fresh({ 'a', 'b' })
    local calls = 0
    api.nvim_buf_attach(b, false, { on_lines = function() calls = calls + 1 end })
    api.nvim_buf_set_lines(b, 0, 1, false, { 'x', 'y' })
    eq(calls >= 1, true)
  end)
  it('marks', function()
    local b = fresh({ 'abc', 'def' })
    api.nvim_buf_set_mark(b, 'a', 2, 1, {})
    eq(api.nvim_buf_get_mark(b, 'a'), { 2, 1 })
  end)
  it('call_function', function()
    eq(api.nvim_call_function('toupper', { 'a' }), 'A')
  end)
end)

describe('filetype and highlight by name', function()
  it('vim.filetype.match', function()
    eq(vim.filetype.match({ filename = 'foo.lua' }), 'lua')
    vim.filetype.add({ extension = { artemisx = 'artemisft' } })
    eq(vim.filetype.match({ filename = 'a.artemisx' }), 'artemisft')
  end)
  it('nvim_get_hl_by_name', function()
    vim.api.nvim_set_hl(0, 'ArtemisHlT', { fg = 0x112233, bold = true })
    local hl = vim.api.nvim_get_hl_by_name('ArtemisHlT', true)
    eq(hl.foreground, 0x112233)
    eq(hl.bold, true)
  end)
end)

describe('highlight commands', function()
  it('accepts guifg=None like Neovim', function()
    vim.cmd('highlight ArtemisNone guifg=None guibg=NONE')
    eq(vim.fn.hlexists('ArtemisNone'), 1)
  end)
  it('nvim_set_hl with "None"', function()
    vim.api.nvim_set_hl(0, 'ArtemisNone2', { fg = 'None', bg = 'None' })
    eq(vim.fn.hlexists('ArtemisNone2'), 1)
  end)
end)
