describe('stdlib', function()
  it('split', function() eq(vim.split('a,b,c', ','), { 'a', 'b', 'c' }) end)
  it('tbl_extend', function() eq(vim.tbl_extend('force', { a = 1 }, { b = 2 }), { a = 1, b = 2 }) end)
  it('iter', function() eq(vim.iter({ 1, 2, 3 }):map(function(x) return x * 2 end):totable(), { 2, 4, 6 }) end)
  it('trim', function() eq(vim.trim('  x '), 'x') end)
  it('inspect', function() eq(vim.inspect({ 1, 2 }), '{ 1, 2 }') end)
  it('deepcopy', function() eq(vim.deepcopy({ a = { 1 } }), { a = { 1 } }) end)
  it('uri', function() eq(vim.uri_from_fname('/tmp/a b'), 'file:///tmp/a%20b') end)
end)
