local api = vim.api
local function fresh()
  vim.cmd('enew!')
  return api.nvim_get_current_buf()
end

describe('buffer lines', function()
  it('set/get lines', function()
    local b = fresh()
    api.nvim_buf_set_lines(b, 0, -1, false, { 'a', 'b', 'c' })
    eq(api.nvim_buf_get_lines(b, 0, -1, false), { 'a', 'b', 'c' })
    eq(api.nvim_buf_line_count(b), 3)
  end)
  it('replace middle', function()
    local b = fresh()
    api.nvim_buf_set_lines(b, 0, -1, false, { 'a', 'b', 'c' })
    api.nvim_buf_set_lines(b, 1, 2, false, { 'x', 'y' })
    eq(api.nvim_buf_get_lines(b, 0, -1, false), { 'a', 'x', 'y', 'c' })
    api.nvim_buf_set_lines(b, 1, 3, false, {})
    eq(api.nvim_buf_get_lines(b, 0, -1, false), { 'a', 'c' })
  end)
  it('append with -1', function()
    local b = fresh()
    api.nvim_buf_set_lines(b, 0, -1, false, { 'a' })
    api.nvim_buf_set_lines(b, -1, -1, false, { 'z' })
    eq(api.nvim_buf_get_lines(b, 0, -1, false), { 'a', 'z' })
  end)
  it('negative get', function()
    local b = fresh()
    api.nvim_buf_set_lines(b, 0, -1, false, { 'a', 'b', 'c' })
    eq(api.nvim_buf_get_lines(b, -2, -1, false), { 'c' })
    eq(api.nvim_buf_get_lines(b, 1, 100, false), { 'b', 'c' })
  end)
  it('strict out of bounds', function()
    local b = fresh()
    local ok = pcall(api.nvim_buf_get_lines, b, 0, 100, true)
    eq(ok, false)
  end)
  it('set_text / get_text', function()
    local b = fresh()
    api.nvim_buf_set_lines(b, 0, -1, false, { 'hello world', 'second' })
    eq(api.nvim_buf_get_text(b, 0, 6, 0, 11, {}), { 'world' })
    api.nvim_buf_set_text(b, 0, 0, 0, 5, { 'HEY' })
    eq(api.nvim_buf_get_lines(b, 0, 1, false), { 'HEY world' })
    api.nvim_buf_set_text(b, 0, 3, 1, 3, { ' / ' })
    eq(api.nvim_buf_get_lines(b, 0, -1, false), { 'HEY / ond' })
  end)
  it('validity and names', function()
    local b = fresh()
    eq(api.nvim_buf_is_valid(b), true)
    eq(api.nvim_buf_is_valid(99999), false)
    eq(api.nvim_buf_get_name(b), '')
    local nb = api.nvim_create_buf(false, true)
    eq(api.nvim_buf_is_valid(nb), true)
    eq(vim.fn.getbufvar(nb, '&buftype'), 'nofile')
    eq(api.nvim_get_current_buf(), b)
  end)
  it('buf_call', function()
    local b = fresh()
    local nb = api.nvim_create_buf(false, true)
    api.nvim_buf_set_lines(nb, 0, -1, false, { 'in other' })
    local r = api.nvim_buf_call(nb, function() return vim.fn.getline(1) end)
    eq(r, 'in other')
    eq(api.nvim_get_current_buf(), b)
  end)
  it('buffer variables', function()
    local b = fresh()
    api.nvim_buf_set_var(b, 'foo', { 1, 2 })
    eq(api.nvim_buf_get_var(b, 'foo'), { 1, 2 })
    api.nvim_buf_del_var(b, 'foo')
    eq(pcall(api.nvim_buf_get_var, b, 'foo'), false)
  end)
end)

describe('windows', function()
  it('cursor', function()
    local b = fresh()
    api.nvim_buf_set_lines(b, 0, -1, false, { 'abc', 'defg' })
    api.nvim_win_set_cursor(0, { 2, 2 })
    eq(api.nvim_win_get_cursor(0), { 2, 2 })
    eq(api.nvim_get_current_line(), 'defg')
  end)
  it('split and list', function()
    fresh()
    local before = #api.nvim_list_wins()
    vim.cmd('split')
    eq(#api.nvim_list_wins(), before + 1)
    local w = api.nvim_get_current_win()
    eq(api.nvim_win_is_valid(w), true)
    api.nvim_win_close(w, true)
    eq(api.nvim_win_is_valid(w), false)
  end)
end)
