local api = vim.api

describe('user commands', function()
  it('callback with args', function()
    local got
    api.nvim_create_user_command('ArtemisT1', function(o) got = o end, { nargs = '*', bang = true })
    vim.cmd('ArtemisT1! a b "c d"')
    eq(got.args, 'a b "c d"')
    eq(got.bang, true)
    eq(got.fargs[1], 'a')
    eq(got.name, 'ArtemisT1')
    api.nvim_del_user_command('ArtemisT1')
    eq(pcall(vim.cmd, 'ArtemisT1'), false)
  end)
  it('string command', function()
    api.nvim_create_user_command('ArtemisT2', 'let g:artemis_t2 = 1', {})
    vim.cmd('ArtemisT2')
    eq(vim.g.artemis_t2, 1)
  end)
  it('range and count', function()
    vim.cmd('enew!')
    api.nvim_buf_set_lines(0, 0, -1, false, { 'a', 'b', 'c' })
    local got
    api.nvim_create_user_command('ArtemisT3', function(o) got = o end, { range = true })
    vim.cmd('2,3ArtemisT3')
    eq({ got.line1, got.line2, got.range }, { 2, 3, 2 })
  end)
end)

describe('autocmds', function()
  it('callback on User event', function()
    local g = api.nvim_create_augroup('ArtemisG1', { clear = true })
    local hits = 0
    api.nvim_create_autocmd('User', {
      group = g, pattern = 'ArtemisEv',
      callback = function(a) hits = hits + 1; eq(a.event, 'User') end,
    })
    api.nvim_exec_autocmds('User', { pattern = 'ArtemisEv' })
    api.nvim_exec_autocmds('User', { pattern = 'ArtemisEv' })
    eq(hits, 2)
  end)
  it('once', function()
    local hits = 0
    api.nvim_create_autocmd('User', { pattern = 'ArtemisOnce', once = true, callback = function() hits = hits + 1 end })
    api.nvim_exec_autocmds('User', { pattern = 'ArtemisOnce' })
    api.nvim_exec_autocmds('User', { pattern = 'ArtemisOnce' })
    eq(hits, 1)
  end)
  it('clear augroup on recreate', function()
    local hits = 0
    for _ = 1, 2 do
      local g = api.nvim_create_augroup('ArtemisG2', { clear = true })
      api.nvim_create_autocmd('User', { group = g, pattern = 'ArtemisEv2', callback = function() hits = hits + 1 end })
    end
    api.nvim_exec_autocmds('User', { pattern = 'ArtemisEv2' })
    eq(hits, 1)
  end)
  it('data', function()
    local d
    api.nvim_create_autocmd('User', { pattern = 'ArtemisData', callback = function(a) d = a.data end })
    api.nvim_exec_autocmds('User', { pattern = 'ArtemisData', data = { x = 1 } })
    eq(d, { x = 1 })
  end)
  it('return true removes', function()
    local hits = 0
    api.nvim_create_autocmd('User', { pattern = 'ArtemisRm', callback = function() hits = hits + 1; return true end })
    api.nvim_exec_autocmds('User', { pattern = 'ArtemisRm' })
    api.nvim_exec_autocmds('User', { pattern = 'ArtemisRm' })
    eq(hits, 1)
  end)
end)

describe('keymaps', function()
  it('string rhs', function()
    vim.keymap.set('n', '<Space>aq', ':let g:artemis_km = 1<CR>', { silent = true })
    eq(vim.fn.maparg('<Space>aq', 'n'), ':let g:artemis_km = 1<CR>')
    vim.keymap.del('n', '<Space>aq')
    eq(vim.fn.maparg('<Space>aq', 'n'), '')
  end)
  it('function rhs runs via feedkeys', function()
    local hit = 0
    vim.keymap.set('n', '<F9>', function() hit = hit + 1 end)
    vim.api.nvim_feedkeys(vim.api.nvim_replace_termcodes('<F9>', true, false, true), 'x', false)
    eq(hit, 1)
  end)
  it('multiple modes + buffer-local', function()
    vim.cmd('enew!')
    vim.keymap.set({ 'n', 'x' }, '<Space>bb', ':echo 1<CR>', { buffer = true })
    eq(vim.fn.maparg('<Space>bb', 'n') ~= '', true)
    eq(vim.fn.maparg('<Space>bb', 'x') ~= '', true)
    vim.cmd('enew!')
    eq(vim.fn.maparg('<Space>bb', 'n'), '')
  end)
  it('rhs with bar', function()
    vim.keymap.set('n', '<Space>cc', ':echo 1 | echo 2<CR>')
    eq(vim.fn.maparg('<Space>cc', 'n'), ':echo 1 | echo 2<CR>')
  end)
end)

describe('misc api', function()
  it('replace_termcodes', function()
    eq(api.nvim_replace_termcodes('a<CR>b', true, false, true), 'a\rb')
    eq(api.nvim_replace_termcodes('<Esc>', true, false, true), '\27')
  end)
  it('exec2 output', function()
    eq(api.nvim_exec2('echo "hi"', { output = true }).output, 'hi')
  end)
  it('nvim_cmd', function()
    api.nvim_cmd({ cmd = 'let', args = { 'g:artemis_c', '=', '3' } }, {})
    eq(vim.g.artemis_c, 3)
  end)
  it('vim.cmd.xxx', function()
    vim.cmd.let('g:artemis_c2 = 5')
    eq(vim.g.artemis_c2, 5)
  end)
  it('schedule + wait', function()
    local done = false
    vim.schedule(function() done = true end)
    eq(vim.wait(500, function() return done end, 10), true)
  end)
  it('defer_fn', function()
    local done = false
    vim.defer_fn(function() done = true end, 10)
    eq(vim.wait(1000, function() return done end, 10), true)
  end)
  it('str_utfindex', function()
    eq(vim.str_utfindex('aあb', 4), 2)
    eq(vim.str_byteindex('aあb', 2), 4)
  end)
end)
